def collect():

    result = subprocess.run(
        [sys.executable, "-m", "piplicenses", "--from=mixed", "--format=json", "--with-urls"],
        capture_output=True, text=True, check=True,
    )

    packages = [p for p in json.loads(result.stdout) if p["Name"] not in TOOLS]

    return sorted(packages, key=lambda p: p["Name"].lower())


def needs_review(package):

    license_text = package["License"].upper()

    return any(word in license_text for word in COPYLEFT) and package["Name"] not in REVIEWED


def write(packages):

    lines = [
        "# Third-party licenses",
        "",
        "Sophia itself is MIT licensed (see LICENSE). It depends on the packages below, installed",
        "by pip from PyPI, and downloads the models listed at the end. Generated by",
        "`python scripts/licenses.py` from a macOS install; Windows adds pywin32 (PSF),",
        "comtypes (MIT) and uiautomation (Apache-2.0) and leaves out PyObjC (MIT).",
        "",
        "## Reviewed copyleft and other notable licenses",
        "",
        "| Package | Note |",
        "| --- | --- |",
    ]

    for name, note in REVIEWED.items():
        lines.append(f"| {name} | {note} |")

    lines += ["", "## All Python packages", "", "| Package | Version | License |", "| --- | --- | --- |"]

    for p in packages:

        name = f"[{p['Name']}]({p['URL']})" if p.get("URL") and p["URL"] != "UNKNOWN" else p["Name"]

        lines.append(f"| {name} | {p['Version']} | {p['License'].replace('|', '/')} |")

    lines += ["", MODELS]

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")

    print(f"Wrote {OUTPUT.name} ({len(packages)} packages)")


def main(argv=None):

    argv = sys.argv[1:] if argv is None else argv

    packages = collect()

    unreviewed = [p for p in packages if needs_review(p)]

    if "--check" in argv:

        for p in unreviewed:
            print(f"Unreviewed license: {p['Name']} {p['Version']}: {p['License']}")

        if unreviewed:
            print("Review them and add them to REVIEWED in scripts/licenses.py.")
            return 1

        print(f"Licenses OK ({len(packages)} packages)")

        return 0

    write(packages)

    return 0


if __name__ == "__main__":
    sys.exit(main())
